CREATE TABLE CLIENTE (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRES VARCHAR2(80 CHAR) NOT NULL,
    APELLIDOS VARCHAR2(80 CHAR) NOT NULL,
    DOCUMENTO VARCHAR2(20 CHAR) NOT NULL,
    TELEFONO VARCHAR2(20 CHAR),
    CORREO VARCHAR2(120 CHAR),
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
    CONSTRAINT UK_CLIENTE_DOCUMENTO UNIQUE (DOCUMENTO),
    CONSTRAINT CK_CLIENTE_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);

CREATE TABLE SERVICIO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(7 CHAR) NOT NULL,
    NOMBRE VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(250 CHAR),
    PRECIO NUMBER(10, 2) NOT NULL,
    DURACION_MINUTOS NUMBER(3) NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_SERVICIO PRIMARY KEY (ID),
    CONSTRAINT UK_SERVICIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_SERVICIO_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CK_SERVICIO_DURACION CHECK (DURACION_MINUTOS BETWEEN 15 AND 480),
    CONSTRAINT CK_SERVICIO_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);

CREATE TABLE VEHICULO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE_ID NUMBER(19) NOT NULL,
    PLACA VARCHAR2(7 CHAR) NOT NULL,
    MARCA VARCHAR2(60 CHAR) NOT NULL,
    MODELO VARCHAR2(60 CHAR) NOT NULL,
    ANIO NUMBER(4) NOT NULL,
    KILOMETRAJE_ACTUAL NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VEHICULO PRIMARY KEY (ID),
    CONSTRAINT UK_VEHICULO_PLACA UNIQUE (PLACA),
    CONSTRAINT CK_VEHICULO_ANIO CHECK (ANIO BETWEEN 1990 AND 2027),
    CONSTRAINT CK_VEHICULO_KILOMETRAJE CHECK (KILOMETRAJE_ACTUAL >= 0),
    CONSTRAINT FK_VEHICULO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID)
);

CREATE TABLE USUARIOS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(120 CHAR) NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);

CREATE TABLE ROLES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UK_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO_ROLES (
    USUARIO_ID NUMBER(19) NOT NULL,
    ROL_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_USUARIO_ROLES PRIMARY KEY (USUARIO_ID, ROL_ID),
    CONSTRAINT FK_USUARIO_ROLES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT FK_USUARIO_ROLES_ROL FOREIGN KEY (ROL_ID) REFERENCES ROLES (ID)
);

CREATE TABLE ORDEN_SERVICIO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(20 CHAR) NOT NULL,
    VEHICULO_ID NUMBER(19) NOT NULL,
    KILOMETRAJE NUMBER(10) NOT NULL,
    FECHA_CREACION TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'REGISTRADA' NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL,
    MOTIVO_ANULACION VARCHAR2(200 CHAR),
    ANULADA_EN TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_ORDEN_SERVICIO PRIMARY KEY (ID),
    CONSTRAINT UK_ORDEN_SERVICIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_ORDEN_SERVICIO_KILOMETRAJE CHECK (KILOMETRAJE >= 0),
    CONSTRAINT CK_ORDEN_SERVICIO_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'ANULADA')),
    CONSTRAINT CK_ORDEN_SERVICIO_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT FK_ORDEN_SERVICIO_VEHICULO FOREIGN KEY (VEHICULO_ID) REFERENCES VEHICULO (ID)
);

CREATE TABLE DETALLE_ORDEN (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORDEN_ID NUMBER(19) NOT NULL,
    SERVICIO_ID NUMBER(19) NOT NULL,
    CANTIDAD NUMBER(2) NOT NULL,
    PRECIO_UNITARIO NUMBER(10, 2) NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    CONSTRAINT PK_DETALLE_ORDEN PRIMARY KEY (ID),
    CONSTRAINT UK_DETALLE_ORDEN_SERVICIO UNIQUE (ORDEN_ID, SERVICIO_ID),
    CONSTRAINT CK_DETALLE_ORDEN_CANTIDAD CHECK (CANTIDAD BETWEEN 1 AND 5),
    CONSTRAINT CK_DETALLE_ORDEN_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CK_DETALLE_ORDEN_SUBTOTAL CHECK (SUBTOTAL > 0),
    CONSTRAINT FK_DETALLE_ORDEN_ORDEN FOREIGN KEY (ORDEN_ID) REFERENCES ORDEN_SERVICIO (ID),
    CONSTRAINT FK_DETALLE_ORDEN_SERVICIO FOREIGN KEY (SERVICIO_ID) REFERENCES SERVICIO (ID)
);

CREATE INDEX IX_VEHICULO_CLIENTE ON VEHICULO (CLIENTE_ID);
CREATE INDEX IX_ORDEN_SERVICIO_VEHICULO_FECHA ON ORDEN_SERVICIO (VEHICULO_ID, FECHA_CREACION);
CREATE INDEX IX_ORDEN_SERVICIO_ESTADO_FECHA ON ORDEN_SERVICIO (ESTADO, FECHA_CREACION);
CREATE INDEX IX_DETALLE_ORDEN_SERVICIO ON DETALLE_ORDEN (SERVICIO_ID);

